<p>换句话说，<strong>在马可·波罗回到意大利之前，意大利已经存在面食生产和消费的历史记录。</strong></p>
<p>不过，"马可·波罗带回意大利面"这个传说本身的形成过程更加复杂。</p>
<p>人们经常把它完全归因于美国面食行业期刊 <em>Macaroni Journal</em> 在 1929
年刊登的一则故事。那篇文章确实推动了这个说法的传播，但历史学家 Massimo
Montanari 认为，它还可以追溯到更早的文本：Giovanni Battista Ramusio 在
1559
年出版的马可·波罗游记版本中，对旅行者关于食物的描述产生了一种容易引起误解的解读。</p>
<p>因此，更准确的说法是：<strong>这是一个在不同历史时期不断被建构、解释并重新传播的传说。</strong></p>
<h3>那中国 4,000 年前的 noodles 呢？</h3>
<p>否定马可·波罗传说，并不意味着否定中国面食传统的悠久历史。</p>
<p>在中国西北部的喇家遗址（Lajia），考古学家发现了被解释为约 4,000 年前
noodles 的遗存。2005 年发表在 <em>Nature</em>
上的研究将其描述为一种以小米为原料的食品。</p>
<p>这一发现非常重要，但语言上的准确性同样重要。</p>
<p>为了帮助读者理解形状，有时人们会把它称为"4,000 年前的
spaghetti"。但这种说法很容易把两种不同的食物和饮食传统直接重叠起来。</p>
<p>关于这些遗存的具体原料和制作方式，学术界也存在讨论。实验研究曾质疑仅使用小米面团能否制作出拉伸型面条，后续研究则进一步讨论了可能使用的材料和加工技术。</p>
<p>因此，这些考古发现能够证明一种非常古老的面条状食品传统，<strong>但仅凭这些遗存，并不能证明今天的意大利
spaghetti 直接起源于它。</strong></p>
<p>如果要证明两者之间存在历史传播关系，还需要能够连接不同地区、时期、接触与技术变化的证据链。仅仅"长得像"并不足够。</p>
<p>同样，在现有证据下，直接断言世界各地所有面条传统都彼此完全独立，也会显得过于绝对。</p>
<h2>06. 番茄，其实来得很晚</h2>
<p><img alt="番茄意大利面的基本食材" src="https://luxureat.cn/wp-content/themes/luxureat-wordpress-theme/assets/media/academy/spaghetti-history-tomato.webp" /></p>
<p><em>图片：番茄意大利面的基本食材 / Wikimedia Commons。</em></p>
<p>今天，我们几乎会本能地把 spaghetti 和番茄联系在一起。</p>
<p>但从历史来看，面食已经存在了几个世纪之后，番茄才进入这段故事。</p>
<p>番茄原产于美洲，在欧洲与美洲建立联系之后才进入欧洲，并逐渐被用于烹饪，最终成为许多意大利菜肴的重要组成部分。</p>
<p>关于番茄与面食搭配的重要历史记录之一，来自 Ippolito Cavalcanti 的
<em>Cucina teorico-pratica</em>。这本书首次出版于 1837 年。</p>
<p>不过，需要区分"一本书的初版年份"和"某一道具体菜谱出现的年份"。Storia e
Memoria di Bologna 的相关历史整理将 <em>vermicelli al pomodoro</em> 的记录放在
1839 年版本中。</p>
<blockquote>
<p><strong>面食 → 番茄 → 番茄意大利面</strong>
今天看起来仿佛从来就应该在一起的组合，其实来自不同历史轨迹的相遇。</p>
</blockquote>
<p>当然，一道菜第一次被印刷在食谱中，也不意味着那就是它真正被"发明"的时间。家庭厨房、街头摊贩与餐饮店里的实际做法，完全可能早于书面记录。</p>
<h2>一种诞生于意大利、却始终与世界相连的传统</h2>
<p>"谁发明了 spaghetti？"这个问题，似乎期待一个人的名字。</p>
<p>但历史资料真正带给我们的，却是一系列地点、职业、贸易网络和日常习惯。</p>
<p>中世纪西西里留下了重要的干制面食生产记录；热那亚让我们看到贸易网络的作用；那不勒斯与坎帕尼亚则在面食生产、大众消费和城市文化的形成中发挥了决定性作用；亚洲悠久的面条传统，则提醒我们：人类制作细长条状食品的历史，比任何单一的起源故事都更加复杂。</p>
<p>这种复杂性并不会削弱 spaghetti 的意大利身份，反而让它更加有趣。</p>
<p>一种饮食传统并不一定诞生于某一个瞬间。它是在一代又一代生产者、厨师、商贩和食客的重复实践中逐渐形成的，并通过原料选择、口感、酱汁和共同进餐的方式获得自己的特征。</p>
