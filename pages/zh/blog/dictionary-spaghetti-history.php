<p>一盘意大利面，或许是最能让人立刻联想到意大利的食物之一。想象一下，用叉子卷起细长的面条，配上番茄与罗勒—简单的食材，却足以让人辨认出一种已经走向世界的饮食文化。</p>
<p>但当我们追问"究竟是谁发明了 spaghetti？"时，答案却没有想象中那么简单。</p>
<p>它诞生于西西里？那不勒斯？还是像著名传说所说的那样，由马可·波罗从中国带回意大利？</p>
<p>我们并不知道某一位明确的"意大利面发明者"，也无法确定一个唯一的诞生地点和日期。不过，我们可以沿着几个关键节点重新理解它的历史：中世纪西西里的干制面食生产、地中海贸易网络、那不勒斯面食文化的发展，以及今天我们所熟悉的"spaghetti"这一名称的出现。</p>
<p>理解这段历史，首先要区分三个彼此相关、却并不完全相同的问题：<strong>面食从哪里来、长条形面食从哪里来，以及意大利
spaghetti 传统是如何形成的。</strong></p>
<h2>01. 中世纪西西里：一条重要的历史证据</h2>
<blockquote>
<p><strong>1154 · 西西里 Trabia</strong>
地理学家 al-Idrisi 记录了当地规模化生产
<em>itriyya</em>—一种可保存、可运输的细长干制面食。</p>
</blockquote>
<p>其中一份最重要的历史文献，把我们带到 1154 年的
Trabia—一个位于巴勒莫附近、西西里北部海岸的小镇。</p>
<p>当时在诺曼国王鲁杰罗二世宫廷工作的地理学家 al-Idrisi
描述，当地大量生产一种名为 <em>itriyya</em>
的食品，通常被解释为细长的干制面食。这些面食会通过地中海航线运往卡拉布里亚以及其他穆斯林和基督教地区。</p>
<p>这里真正重要的，不只是"面条已经存在"，而是它已经形成了具有商业规模的生产。Trabia
的面食能够长期保存、方便运输，而且需求已经超出了当地市场。这份记录也与西西里和阿拉伯世界之间长期的文化与贸易联系有关；研究者认为，这些联系在干制面食的传播过程中具有重要作用。</p>
<p>那么，我们是否可以直接说"spaghetti 就是在 Trabia 发明的"？</p>
<p>答案仍然是否定的。</p>
<p>这份文献能够证明的是：<strong>12
世纪的西西里已经存在有组织的、与长条形面食家族相近的干制面食生产。</strong>但它没有告诉我们谁是第一个生产者，也没有描述一种与今天
spaghetti 完全相同、已经标准化的产品。</p>
<p><strong>Trabia 是 spaghetti 历史中的一个重要坐标，但不是一张"出生证明"。</strong></p>
<h2>02. 干燥技术：让面食能够旅行</h2>
<p>新鲜面团与干燥食品，在保存和运输能力上有着完全不同的可能性。</p>
<p>降低水分意味着面食可以保存更长时间，也更容易长途运输。在交通缓慢的时代，这一点尤其重要。</p>
<p>因此，干制面食的发展也逐渐与港口和贸易网络联系在一起。除了西西里之外，热那亚同样留下了重要证据。1279
年的一份热那亚财产清单中，在一名士兵的物品里记录了一个装有 <em>maccheroni</em>
的容器。</p>
<p>这意味着，在马可·波罗从亚洲返回之前，意大利已经存在面食相关的历史记录。</p>
<blockquote>
<p><strong>西西里 → 地中海 → 热那亚 → 那不勒斯</strong></p>
</blockquote>
<p>不过，阅读中世纪文献时也必须谨慎。当时的 <em>maccheroni</em>
等词汇，并不一定对应今天我们看到这些名称时所想到的具体形状。</p>
<p>名称、形态与制作方法都会随着时间变化。用今天意大利面工厂的产品目录去理解中世纪词汇，很容易得到过于简单的结论。</p>
<h2>03. 那不勒斯：当面食成为大众食物</h2>
<p><img alt="约1880年的那不勒斯食面者" src="https://luxureat.cn/wp-content/themes/luxureat-wordpress-theme/assets/media/academy/spaghetti-history-naples.webp" /></p>
<p><em>图片：Giorgio Sommer，"Macaroni eaters, Naples"，约 1880 年 / Wikimedia
Commons。</em></p>
<blockquote>
<p><strong>从 "mangiafoglia" 到 "mangiamaccheroni"</strong></p>
</blockquote>
<p>如果说西西里为我们提供了重要的中世纪历史证据，那么那不勒斯的关键意义，则在于它如何把面食逐渐变成日常食物和集体文化符号。</p>
<p>17 世纪，那不勒斯人的饮食习惯发生了明显变化。历史学家 Emilio Sereni
曾用从 <em>mangiafoglia</em>（"吃菜叶的人"）到
<em>mangiamaccheroni</em>（"吃通心粉/面食的人"）的转变来描述这一过程。</p>
<p>这些称呼反映了面食在大众饮食中越来越重要的地位，也与当时的经济环境和生产方式变化有关。</p>
<p>此后几个世纪，坎帕尼亚地区的面食生产不断发展，Gragnano
等生产中心进一步提高了面食的供应量。面食也进入了城市街头生活：人们可以买到已经煮好的面，快速食用，并搭配磨碎的奶酪和胡椒。</p>
<p>历史图像中的 <em>mangiamaccheroni</em>、街头面食摊贩和
Pulcinella，都说明这种食物已经深深进入那不勒斯的城市文化。到了 18---19
世纪，这种形象开始超越城市本身，逐渐成为更广泛的意大利饮食符号。</p>
<p>因此，那不勒斯的贡献远远不只是"谁最先做出了一根长面条"。</p>
<p>它真正重要的地方，是让面食成为一种<strong>共同的日常习惯、一种城市生活方式，以及一种饮食身份。</strong></p>
<h2>04. "Spaghetti"这个名字什么时候出现？</h2>
<blockquote>
<p><strong>1817</strong></p>
<p><strong>"Spaghetti"一词至少在 1817 年已经有文献记录。</strong></p>
</blockquote>
<p><em>Spaghetti</em> 来自意大利语 <em>spago</em>，意为细绳；<em>spaghetti</em>
可以理解为"小细绳"，非常直观地描述了这种面食的形态。</p>
<p>一些通俗资料经常提到 1824 年，并把这个词与 Antonio Viviani 的诗作 <em>Li
maccheroni di Napoli</em> 联系起来。但把 1824 年直接称为"spaghetti
一词第一次出现的年份"并不严谨。</p>
<p>AtLiTeG 项目的《意大利美食语言历史词典》（<em>Vocabolario storico della
lingua italiana della gastronomia</em>）指出，在 1817 年 6 月 14 日的
<em>Giornale del Regno delle Due Sicilie</em> 中，已经出现了 spaghetti
一词，当时它出现在一则为 Real Casa degli Invalidi 供应食品的公告中。</p>
<p>因此，更准确的说法是：</p>
<p><strong>"Spaghetti"这一名称至少从 1817 年起已有文献记录。</strong></p>
<p>当然，一个名称第一次出现在现存文献中的时间，并不等于这种食物真正诞生的时间。食物完全可能早于名称存在，也可能曾经使用其他名字。</p>
<h2>05. 马可·波罗把 spaghetti 从中国带回了意大利吗？</h2>
<p><img alt="马可·波罗肖像" src="https://luxureat.cn/wp-content/themes/luxureat-wordpress-theme/assets/media/academy/spaghetti-history-marco-polo.webp" /></p>
<p><em>图片：马可·波罗推定肖像，16 世纪 / Wikimedia Commons。</em></p>
<h3>没有—但真实的历史反而更加有趣。</h3>
<p>这是一个流传极广的故事：马可·波罗在中国发现了面条，并在 1295
年结束亚洲旅行后把它带回意大利。</p>
<p>但更早的意大利文献已经足以否定这种简单的叙述。</p>
