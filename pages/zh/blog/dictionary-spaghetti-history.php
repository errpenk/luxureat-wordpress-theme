而言，向国际消费者讲述意大利饮食文化，也意味着准确地理解并呈现这些历史。</p>
<p>这既是对其他饮食文化的尊重，也是解释"什么让意大利饮食成为意大利饮食"的一种方式。</p>
<p>Spaghetti 并不需要一个传奇的发明者。</p>
<p>它背后有一代又一代的制面师与厨师，有跨越地中海的贸易路线，有家庭餐桌，也有让面食成为日常生活一部分的城市。</p>
