<p>The history of the legend itself is more complicated. It is often
attributed entirely to a story published in 1929 in the American trade
publication <em>Macaroni Journal</em>. That publication certainly helped
popularize it, but historian Massimo Montanari identifies earlier roots
in Giovanni Battista Ramusio's 1559 edition of Marco Polo's travels,
through a misleading interpretation of the traveller's references to
food.</p>
<p>It is therefore more accurate to speak of a legend that was gradually
constructed and repeatedly revived.</p>
<h3>What about 4,000-year-old Chinese noodles?</h3>
<p>Rejecting the Marco Polo legend does not mean ignoring the antiquity of
Chinese food traditions.</p>
<p>At the archaeological site of Lajia in northwestern China, remains
interpreted as noodles dating back around 4,000 years were discovered. A
study published in <em>Nature</em> in 2005 described them as a millet-based
preparation.</p>
<p>The discovery is extraordinary, but the language used to describe it
matters. Calling them "spaghetti" may help us imagine their shape, but
it risks merging distinct foods and culinary traditions.</p>
<p>The interpretation of their composition and production method has also
been debated. An experimental study challenged whether stretched noodles
could be made from millet-only dough, while later research further
investigated the possible materials and techniques.</p>
<p>These remains document an extremely ancient preparation. <strong>On their own,
they do not demonstrate that Italian spaghetti descended from it.</strong></p>
<p>To establish historical transmission, we would need evidence of the
stages, contacts and transformations involved. Similarity of shape is
not enough. At the same time, claiming complete independence among all
such traditions would also be more categorical than the available
evidence allows.</p>
<h2>06. Tomato came much later</h2>
<p><img alt="Ingredients for spaghetti with tomato sauce" src="https://luxureat.cn/wp-content/themes/luxureat-wordpress-theme/assets/media/academy/spaghetti-history-tomato.webp" /></p>
<p><em>Image: ingredients for spaghetti with tomato sauce / Wikimedia
Commons.</em></p>
<p>Today, spaghetti and tomato seem almost inseparable. Historically,
however, pasta existed for centuries without this sauce.</p>
<p>The tomato is a plant of American origin and entered European cuisine
after contact with the Americas. Its culinary use developed gradually
until it became an essential part of many Italian preparations.</p>
<p>An important reference for pairing tomato with pasta is Ippolito
Cavalcanti, author of <em>Cucina teorico-pratica</em>, first published in 1837.
The first edition of a book must be distinguished from the appearance of
individual recipes: a reconstruction published by Storia e Memoria di
Bologna places <em>vermicelli al pomodoro</em> in the 1839 edition.</p>
<blockquote>
<p><strong>Pasta → Tomato → Spaghetti with tomato sauce</strong>
A dish that now seems timeless is actually the result of different
histories coming together.</p>
</blockquote>
<p>Here too, a printed recipe documents a practice without necessarily
marking its invention. Home kitchens, workshops and street vendors may
have preceded the cookbooks.</p>
<h2>An Italian tradition with a history open to the world</h2>
<p>The question "who invented spaghetti?" looks for a name. The sources
instead give us places, crafts, trade routes and habits.</p>
<p>Medieval Sicily documents important dried-pasta production. Genoa shows
the role of commercial networks. Naples and Campania were decisive in
the development of production and popular consumption. Asian traditions
demonstrate just how ancient and complex the history of thread-shaped
foods can be.</p>
<p>This complexity makes the Italian identity of spaghetti more
interesting, not less. A culinary tradition takes shape through the
repeated work of people who produce, cook, sell and eat; it develops its
character through ingredients, textures, sauces and the occasions on
which food is shared.</p>
<p>For those of us at <strong>LuxurEat</strong>, telling the story of Italian food
culture to an international audience means understanding this history
and presenting it accurately. It means respecting other culinary
cultures while explaining what makes our own recognizable.</p>
<p>Spaghetti does not need a legendary inventor. Behind it stand
generations of pasta makers and cooks, trade routes, family tables and
cities that made it an everyday food.</p>
<p><strong>That long experience still survives today in one very simple gesture:
wrapping a strand of pasta around a fork.</strong></p></div></section>
