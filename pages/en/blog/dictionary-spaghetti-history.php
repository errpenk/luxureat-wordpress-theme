    <section class="lux-reader-hero"><div class="lux-reader-hero-copy"><div class="lux-reader-meta-grid"><span>Italian Food Dictionary</span><span>Italian Food Dictionary · 2026</span></div><h1 id="lux-reader-title">Who Invented Spaghetti? The Story of an Italian Symbol, from Sicily and Naples to the Legends of China</h1><p class="lux-reader-summary">From the dried pasta of the medieval Mediterranean to the tables of Naples and its international success, the origins of spaghetti tell a story more fascinating than any legend.</p></div><figure class="lux-reader-cover"><img width="1200" height="900" loading="eager" fetchpriority="high" decoding="async" src="<?php echo esc_url(get_template_directory_uri() . '/assets/media/academy/spaghetti-history-cover.webp'); ?>" alt="Who Invented Spaghetti? The Story of an Italian Symbol, from Sicily and Naples to the Legends of China"></figure></section>
    <section class="lux-reader-content"><aside class="lux-reader-aside"><a href="<?php echo esc_url(luxureat_static_url('en/blog', '')); ?>">Back to Knowledge Blog</a></aside><div class="lux-reader-copy lux-cms-prose"><p><em>Image: "Spaghettata", Roberto De Martino / Wikimedia Commons, public
domain.</em></p>
<p>A plate of spaghetti is one of the most immediate ways to evoke Italy.
Picture the strands wrapped around a fork, dressed with tomato and
basil, and you immediately recognize a food culture that speaks to the
world through simple ingredients.</p>
<p>Yet when we ask who invented spaghetti, the answer becomes far less
obvious. Did it begin in Sicily? In Naples? Or did it come from China,
as the famous story of Marco Polo claims?</p>
<p>We do not know of a single inventor of spaghetti, nor can we identify
one place and one day as its definitive birth. What we can reconstruct
are several decisive stages: dried-pasta production in medieval Sicily,
Mediterranean trade, the development of Neapolitan pasta culture, and
the appearance of the name by which we know it today.</p>
<p>To understand the story, we need to distinguish between three related
but different histories: the origins of pasta, the origins of long
pasta, and the formation of the Italian spaghetti tradition.</p>
<h2>01. Medieval Sicily: a fundamental piece of evidence</h2>
<blockquote>
<p><strong>1154 · Trabia, Sicily</strong>
Al-Idrisi documents an organized production of <em>itriyya</em>, a
thread-like dried pasta that was also made for trade.</p>
</blockquote>
<p>One of the most important documents takes us to 1154 and to Trabia, on
the Sicilian coast near Palermo.</p>
<p>The geographer al-Idrisi, who worked at the court of the Norman king
Roger II, described a place where large quantities of <em>itriyya</em> were
produced, generally interpreted as a thread-like dried pasta. It was
shipped to Calabria and to other Muslim and Christian territories
through Mediterranean trade routes.</p>
<p>The crucial detail is the commercial scale of this production. Pasta
from Trabia was already a food made to travel: it could be preserved and
was sought beyond the place where it was produced. The evidence belongs
to the wider history of contacts between Sicily and the Arab world,
which scholars regard as important in the spread of dried pasta.</p>
<p>Can we therefore say that spaghetti was invented in Trabia? That would
go too far.</p>
<p>The document shows that organized production of a dried pasta related to
the family of long pasta existed in Sicily in the twelfth century. It
does not identify the first producer, nor does it describe a
standardized shape identical to modern spaghetti.</p>
<p><strong>Trabia is a firm point in the historical record, not a birth
certificate.</strong></p>
<h2>02. Drying: the step that allowed pasta to travel</h2>
<p>Fresh dough and a dried food have very different possibilities for
storage and distribution. Reducing moisture allows pasta to last longer
and travel more easily --- an essential advantage in a world where
journeys took time.</p>
<p>The history of dried pasta therefore became intertwined with ports and
trade. Alongside Sicily, Genoa also played an important role. A Genoese
inventory from 1279, listing the possessions of a soldier, mentions a
container of macaroni: further evidence of pasta in Italy before Marco
Polo returned from Asia.</p>
<blockquote>
<p><strong>Sicily → Mediterranean → Genoa → Naples</strong></p>
</blockquote>
<p>Historical vocabulary, however, needs to be treated carefully. Words
such as "maccheroni" did not necessarily refer to the shapes we
associate with them today. Names, forms and preparation methods changed
over time; reading a medieval document as though it were a modern pasta
catalogue can lead to misleading conclusions.</p>
<h2>03. Naples and the transformation of pasta into popular food</h2>
<p><img alt="Macaroni eaters in Naples, c. 1880" src="https://luxureat.cn/wp-content/themes/luxureat-wordpress-theme/assets/media/academy/spaghetti-history-naples.webp" /></p>
<p><em>Image: Giorgio Sommer, "Macaroni eaters, Naples", c. 1880 / Wikimedia
Commons.</em></p>
<blockquote>
<p><strong>From "mangiafoglia" to "mangiamaccheroni"</strong></p>
</blockquote>
<p>If Sicily provides some of the most significant medieval evidence,
Naples occupies a central place in the transformation of pasta into an
everyday food and a collective symbol.</p>
<p>During the seventeenth century, the eating habits of the Neapolitan
population changed profoundly. Historian Emilio Sereni examined this
shift through the transformation of Neapolitans from <em>mangiafoglia</em> ---
"leaf eaters" --- to <em>mangiamaccheroni</em>, or "macaroni eaters". The
expressions reflect the growing importance of pasta in the popular diet
amid economic difficulties and changes in production.</p>
<p>The development of pasta making in Campania, including centres such as
Gragnano, increased the availability of the product over the following
centuries. Pasta also became part of street life: it could be bought
already cooked, eaten quickly, and served with grated cheese and pepper.</p>
<p>Images of macaroni eaters, street vendors and Pulcinella show just how
recognizable pasta had become within Neapolitan culture. Between the
eighteenth and nineteenth centuries, that image acquired a force that
would eventually travel far beyond the city.</p>
<p>Naples' contribution therefore goes far beyond the question of who first
shaped a strand of pasta. It concerns the way pasta became a shared
habit, an urban presence and part of a gastronomic identity.</p>
<h2>04. When did the word "spaghetti" appear?</h2>
<blockquote>
<p><strong>1817</strong></p>
<p><strong>The word "spaghetti" is documented at least as early as 1817.</strong></p>
</blockquote>
<p>The term comes from <em>spago</em>, meaning string or twine: <em>spaghetti</em> are
literally little strings, a name that immediately evokes their shape.</p>
<p>Popular accounts often cite 1824, linking the word to Antonio Viviani's
poem <em>Li maccheroni di Napoli</em>. It is not accurate, however, to present
that year as the first documented use.</p>
<p>The <em>Vocabolario storico della lingua italiana della gastronomia</em>, part
of the AtLiTeG project, records the word in the <em>Giornale del Regno
delle Due Sicilie</em> dated 14 June 1817, in a notice concerning food
supplies for the Real Casa degli Invalidi.</p>
<p>The date of a word is not necessarily the date of the food it describes.
A product may exist before its name appears in a surviving document, or
it may previously have been known under different names.</p>
<h2>05. Did Marco Polo bring spaghetti from China?</h2>
<p><img alt="Portrait of Marco Polo" src="https://luxureat.cn/wp-content/themes/luxureat-wordpress-theme/assets/media/academy/spaghetti-history-marco-polo.webp" /></p>
<p><em>Image: alleged portrait of Marco Polo, 16th century / Wikimedia
Commons.</em></p>
<h3>No --- but the real story is more interesting.</h3>
<p>The story is famous: Marco Polo supposedly discovered pasta in China and
brought it back to Italy when he returned from his travels in 1295.</p>
<p>Earlier Italian evidence is enough to contradict this version.</p>
